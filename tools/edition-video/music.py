"""Procedural lofi-synth / chillwave bed for edition videos.

Original synthesis only: no third-party samples, no copyrighted material.
Dedicated to the public domain under CC0 1.0. Safe for YouTube and X.

    python3 music.py --seconds 400 --out music.wav [--license music-license.txt]

The loop is 16 bars at 80 BPM (~48 s), crossfaded so it tiles cleanly, then
repeated to the requested length, faded, and two-pass loudnorm'd to about
-22 LUFS (quietly under a spoken voiceover).
"""
from __future__ import annotations

import argparse, json, math, os, struct, subprocess, sys, tempfile, wave

import numpy as np

SR = 48000
BPM = 80
BEAT = 60.0 / BPM
BAR = 4 * BEAT
BARS = 16
LOOP_SEC = BARS * BAR  # 48.0
TARGET_LUFS = -22.0
LICENSE_TEXT = """Title: Edition Bed (procedural chillwave)

Source: Generated by tools/edition-video/music.py on the render host.
Method: Original procedural synthesis — warm low-passed pads, electric-piano
chords, a soft sub bass, a swung lofi drum loop, and light vinyl crackle.
No sampled instruments and no third-party recordings were used.

License: CC0 1.0 Universal. This work is dedicated to the public domain.
  https://creativecommons.org/publicdomain/zero/1.0/

Safe for YouTube and X: yes.
"""

# 16 bars, two bars per chord, repeated twice.
# Am9 - Fmaj9 - Cmaj7 - Em7  (i – VI – III – v), mellow and slightly wistful.
# MIDI: A2=45 C3=48 E3=52 G3=55 B3=59 C4=60 D4=62 E4=64 G4=67 A4=69 B4=71
CHORDS = [
    [45, 52, 55, 60, 71],  # Am9
    [45, 52, 55, 60, 71],
    [41, 48, 52, 57, 64],  # Fmaj9
    [41, 48, 52, 57, 64],
    [36, 43, 52, 59, 64],  # Cmaj7
    [36, 43, 52, 59, 64],
    [40, 47, 50, 55, 62],  # Em7
    [40, 47, 50, 55, 62],
] * 2


def midi_hz(n):
    return 440.0 * (2.0 ** ((n - 69) / 12.0))


def adsr(n, sr, a, d, s, r, peak=1.0):
    env = np.zeros(n, dtype=np.float64)
    na, nd, nr = int(a * sr), int(d * sr), int(r * sr)
    na, nd, nr = max(na, 1), max(nd, 1), max(nr, 1)
    ns = max(n - na - nd - nr, 0)
    i = 0
    env[i:i + na] = np.linspace(0, peak, na, endpoint=False); i += na
    if i < n:
        k = min(nd, n - i)
        env[i:i + k] = np.linspace(peak, peak * s, k, endpoint=False); i += k
    if ns and i < n:
        k = min(ns, n - i)
        env[i:i + k] = peak * s; i += k
    if i < n:
        k = n - i
        start = env[i - 1] if i else peak * s
        env[i:] = np.linspace(start, 0, k, endpoint=True)
    return env


def one_pole(x, cutoff, sr=SR):
    """Low-pass, cutoff in Hz. Works on 1-D arrays."""
    x = np.asarray(x, dtype=np.float64)
    if cutoff <= 0:
        return np.zeros_like(x)
    a = math.exp(-2.0 * math.pi * cutoff / sr)
    b = 1.0 - a
    y = np.empty_like(x)
    acc = 0.0
    for i, s in enumerate(x):
        acc = b * s + a * acc
        y[i] = acc
    return y


def highpass(x, cutoff, sr=SR):
    return x - one_pole(x, cutoff, sr)


def blur(x, ms=8, sr=SR):
    k = max(1, int(sr * ms / 1000))
    ker = np.hanning(k * 2 + 1)
    ker /= ker.sum()
    return np.convolve(x, ker, mode="same")


def poly_saw(t, freq, n_harm=12):
    sig = np.zeros_like(t)
    ny = (SR * 0.45)
    for h in range(1, n_harm + 1):
        f = freq * h
        if f >= ny:
            break
        sig += np.sin(2 * np.pi * f * t) / h
    return sig * (2 / math.pi)


def poly_square(t, freq, n_harm=8):
    sig = np.zeros_like(t)
    ny = SR * 0.45
    for h in range(1, n_harm + 1, 2):
        f = freq * h
        if f >= ny:
            break
        sig += np.sin(2 * np.pi * f * t) / h
    return sig * (4 / math.pi)


def sine(t, freq, phase=0.0):
    return np.sin(2 * np.pi * freq * t + phase)


def tanh_sat(x, gain=1.2):
    return np.tanh(x * gain)


def render_loop(rng):
    n = int(round(LOOP_SEC * SR))
    t = np.arange(n) / SR
    left = np.zeros(n)
    right = np.zeros(n)
    bar_n = int(round(BAR * SR))
    beat_n = int(round(BEAT * SR))

    # ---------- pad (warm, detuned, low-passed, slow LFO on cutoff) ----------
    pad_l = np.zeros(n)
    pad_r = np.zeros(n)
    for bi, chord in enumerate(CHORDS):
        start = bi * bar_n
        # overlap into the next bar so chord changes bloom
        length = min(int(BAR * 1.35 * SR), n - start)
        tt = np.arange(length) / SR
        env = adsr(length, SR, a=0.45, d=0.6, s=0.72, r=0.9, peak=1.0)
        # skip the very high notes on the pad; keep it woolly
        notes = chord[:4]
        for j, m in enumerate(notes):
            f = midi_hz(m)
            # two slightly detuned voices, panned
            d1, d2 = 1.0 - 0.0018 * (j + 1), 1.0 + 0.0021 * (j + 1)
            v1 = poly_saw(tt, f * d1, 9)
            v2 = poly_saw(tt, f * d2, 9)
            # a little sine fundamental for body
            body = sine(tt, f * 0.5) * 0.35 + sine(tt, f) * 0.5
            voice = (v1 + v2) * 0.45 + body * 0.55
            voice *= env * (0.55 if j == 0 else 0.4)
            pad_l[start:start + length] += voice * (0.62 if j % 2 == 0 else 0.38)
            pad_r[start:start + length] += voice * (0.38 if j % 2 == 0 else 0.62)
    # slow cutoff wander ~700–1300 Hz
    # cheap: filter the whole pad at 1000 Hz (warm)
    pad_l = one_pole(tanh_sat(pad_l, 0.9), 1600)
    pad_r = one_pole(tanh_sat(pad_r, 0.9), 1680)
    left += pad_l * 0.30
    right += pad_r * 0.30

    # ---------- keys (soft "rhodes": sine + a decaying inharmonic) ----------
    # Play the upper voicing on beats 1 and the "and" of 2, plus a light pickup.
    for bi, chord in enumerate(CHORDS):
        bar_start = bi * bar_n
        # moments in beats: 0.0, 1.5, 3.0 (soft)
        for k, (beat, amp) in enumerate(((0.0, 0.9), (1.5, 0.55), (3.0, 0.35))):
            st = bar_start + int(beat * beat_n)
            length = min(int(1.6 * SR), n - st)
            if length < 200:
                continue
            tt = np.arange(length) / SR
            env = adsr(length, SR, a=0.008, d=0.22, s=0.35, r=0.7, peak=amp)
            tone = np.zeros(length)
            # upper three notes of the voicing
            for mi, m in enumerate(chord[2:]):
                f = midi_hz(m)
                # FM-ish bell: carrier + faint modulator
                car = sine(tt, f)
                mod = sine(tt, f * 2.003) * np.exp(-tt * 6.0) * 0.18
                tone += (car + mod + 0.22 * sine(tt, f * 2) * np.exp(-tt * 8)) * (1.0 - mi * 0.15)
            tone = tone / max(3, len(chord[2:]))
            # very short hammer click
            click = highpass(rng.normal(0, 1, length), 2000) * np.exp(-tt * 80) * 0.04
            voice = (tone + click) * env
            # gentle ping-pong delay (~dotted eighth at 80bpm = 0.75 beat)
            delay = int(0.75 * beat_n)
            lch, rch = voice * 0.72, voice * 0.72
            if st + delay + length <= n:
                # added later via slices
                left[st:st + length] += lch * 0.42
                right[st:st + length] += rch * 0.42
                # delayed opposite
                dl = min(length, n - (st + delay))
                left[st + delay:st + delay + dl] += rch[:dl] * 0.18
                right[st + delay:st + delay + dl] += lch[:dl] * 0.18
            else:
                left[st:st + length] += lch * 0.42
                right[st:st + length] += rch * 0.42

    # ---------- bass (sine + a little triangle, root then fifth) ----------
    for bi, chord in enumerate(CHORDS):
        root = chord[0]  # already around A1–E2 range? A2=45 is good. drop an octave if >= 48
        root = root - 12 if root >= 48 else root
        fifth = root + 7
        bar_start = bi * bar_n
        for beat, note, amp in ((0.0, root, 1.0), (2.0, fifth, 0.7), (3.0, root, 0.45)):
            st = bar_start + int(beat * beat_n)
            length = min(int(1.15 * BEAT * SR), n - st)
            if length < 200:
                continue
            tt = np.arange(length) / SR
            env = adsr(length, SR, a=0.012, d=0.18, s=0.55, r=0.35, peak=amp)
            f = midi_hz(note)
            # almost-triangle via odd harmonics, then heavy lowpass
            wave = sine(tt, f) + 0.35 * sine(tt, f * 2) * 0.3 + 0.12 * sine(tt, f * 3)
            wave = one_pole(wave, 280) * env
            left[st:st + length] += wave * 0.16
            right[st:st + length] += wave * 0.16

    # ---------- drums (soft, swung, lo-fi) ----------
    swing = 0.58  # 16th swing amount (first 16th vs second)
    def swung_16th(si):
        # si is 16th index in the loop
        bar_i = si // 16
        within = si % 16
        beat_i = within // 4
        sub = within % 4  # 0,1,2,3 of the beat
        # pair 16ths: 0+1, 2+3 — delay the off ones
        t0 = bar_i * BAR + beat_i * BEAT + (sub // 2) * (BEAT / 2)
        if sub % 2 == 1:
            t0 += (BEAT / 2) * swing
        else:
            t0 += (BEAT / 2) * (1 - swing) * 0  # on the even 16th, no extra
        # actually even 16ths at 0 and 0.5 of the beat; odd delayed
        return t0

    # Kick on 1 and the "and" of 3 (classic laid-back: 1 and 3)
    # plus a ghost on the 4-and every other bar
    kick_beats = []
    for b in range(BARS):
        kick_beats += [b * 4 + 0, b * 4 + 2]
        if b % 2 == 1:
            kick_beats.append(b * 4 + 3.5)

    def place(sig_l, sig_r, at_sec):
        i = int(at_sec * SR)
        if i >= n:
            return
        ln = min(len(sig_l), n - i)
        left[i:i + ln] += sig_l[:ln]
        right[i:i + ln] += sig_r[:ln]

    for kb in kick_beats:
        st = kb * BEAT
        length = int(0.28 * SR)
        tt = np.arange(length) / SR
        # pitch drop 78 -> 38 Hz
        freq = 78 * np.exp(-tt * 14) + 36
        phase = 2 * np.pi * np.cumsum(freq) / SR
        body = np.sin(phase) * adsr(length, SR, 0.004, 0.05, 0.35, 0.20, 1.0)
        click = highpass(np.sin(2 * np.pi * 700 * tt) * np.exp(-tt * 60), 500) * 0.03
        kick = one_pole(body + click, 180) * 0.38
        kick[:int(0.002 * SR)] *= np.linspace(0, 1, int(0.002 * SR))
        # skip kicks on the last two bars of each 8-bar half for a breath
        bar = int(kb // 4)
        if bar % 8 in (6, 7):
            continue
        place(kick, kick, st)

    # Snare / clap on 2 and 4
    for b in range(BARS * 4):
        if b % 2 == 1:  # beats 2 and 4
            length = int(0.22 * SR)
            tt = np.arange(length) / SR
            noise = highpass(rng.normal(0, 1, length), 1200)
            noise = one_pole(noise, 4200) * adsr(length, SR, 0.001, 0.04, 0.15, 0.12, 1.0)
            body = sine(tt, 190) * np.exp(-tt * 18) * 0.4
            sn = (noise * 0.7 + body) * 0.22
            # slight stereo difference
            place(sn, sn * 0.92 + 0.04 * highpass(rng.normal(0, 1, length), 2000)[:length] * np.exp(-tt * 30),
                  b * BEAT)

    # Hats: 8ths with some 16ths, swung, velocity variation
    for si in range(BARS * 16):
        # pattern: closed hat on every 8th (even 16ths), plus some off 16ths
        even = (si % 2 == 0)
        if not even and rng.random() > 0.45:
            continue
        if not even and si % 4 == 3 and rng.random() > 0.6:
            continue
        at = swung_16th(si)
        length = int((0.045 if even else 0.03) * SR)
        tt = np.arange(length) / SR
        hat = highpass(rng.normal(0, 1, length), 4500)
        hat = one_pole(hat, 7800) * np.exp(-tt * (55 if even else 90))
        fi = min(int(0.002 * SR), length)
        hat[:fi] *= np.linspace(0, 1, fi)
        vel = (0.12 if even else 0.07) * (0.7 + 0.6 * rng.random())
        if si % 16 in (2, 6, 10, 14):  # slightly stronger "and"s
            vel *= 0.8
        # pan a touch
        pan = 0.15 * math.sin(si * 0.7)
        place(hat * vel * (1 - pan), hat * vel * (1 + pan), at)


    # ---------- soft hook in the second half (bars 9-16) ----------
    # A simple descending figure on the chord tones, very present but still under a voice.
    hook_notes = {
        8: [71, 67, 64, 62],   # B4 A? wait B4 G4 E4 D4 over Am/Em area
        9: [71, 69, 67, 64],
        10: [69, 64, 62, 60],
        11: [67, 64, 62, 59],
        12: [72, 71, 67, 64],
        13: [71, 67, 64, 62],
        14: [69, 64, 60, 59],
        15: [67, 64, 62, 59],
    }
    for bi, notes in hook_notes.items():
        for k, m in enumerate(notes):
            st = bi * bar_n + int((k * 1.0) * beat_n)  # one note per beat
            length = min(int(0.95 * BEAT * SR), n - st)
            if length < 200:
                continue
            tt = np.arange(length) / SR
            env = adsr(length, SR, a=0.02, d=0.15, s=0.4, r=0.4, peak=0.7)
            f = midi_hz(m)
            tone = (sine(tt, f) + 0.25 * sine(tt, f * 2) * np.exp(-tt * 5)) * env
            tone = one_pole(tone, 3200)
            # slight delay to the right
            left[st:st + length] += tone * 0.22
            right[st:st + length] += tone * 0.18
            dly = int(0.08 * SR)
            if st + dly + length <= n:
                right[st + dly:st + dly + length] += tone * 0.07

    # ---------- vinyl crackle (sparse, quiet) ----------
    crack = np.zeros(n)
    # occasional pops
    n_pops = int(LOOP_SEC * 4)
    for _ in range(n_pops):
        i = rng.integers(0, n - 40)
        length = int(rng.uniform(8, 40))
        pop = rng.normal(0, 1, length) * np.hanning(length) * rng.uniform(0.02, 0.08)
        crack[i:i + length] += pop
    # bed of faint hiss
    hiss = highpass(rng.normal(0, 1, n), 4000) * 0.008
    hiss = one_pole(hiss, 8000)
    crack = one_pole(crack + hiss, 7000)
    left += crack * 0.7
    right += crack * 0.7

    # ---------- master: gentle highpass, soft clip, stereo width ----------
    left = highpass(left, 28)
    right = highpass(right, 28)
    # mid/side slight widen of highs only would be fancy; simple width:
    mid = (left + right) * 0.5
    side = (left - right) * 0.5
    side *= 1.15
    left, right = mid + side, mid - side
    stereo = np.stack([left, right], axis=1)
    stereo = tanh_sat(stereo, 1.05)
    peak = np.max(np.abs(stereo)) + 1e-9
    stereo = stereo / peak * 0.89
    # Seamless loop: 40 ms equal-power crossfade of tail onto head
    xf = int(0.04 * SR)
    fade_out = np.cos(np.linspace(0, math.pi / 2, xf))[:, None]
    fade_in = np.sin(np.linspace(0, math.pi / 2, xf))[:, None]
    stereo[-xf:] = stereo[-xf:] * fade_out + stereo[:xf] * fade_in
    return stereo


def write_wav(path, stereo, sr=SR):
    """24-bit stereo WAV."""
    stereo = np.clip(stereo, -1.0, 1.0)
    # pack as 24-bit little-endian in a 32-bit container via wave (sampwidth=3)
    ints = np.ascontiguousarray((stereo * 8388607.0).astype(np.int32))
    packed = ints.astype("<i4").tobytes()
    frames = np.frombuffer(packed, dtype=np.uint8).reshape(-1, 4)[:, :3].tobytes()
    with wave.open(path, "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(3)
        w.setframerate(sr)
        w.writeframes(frames)


def loudnorm(src, dst, i=TARGET_LUFS, lra=9.0, tp=-2.0):
    """Two-pass ffmpeg loudnorm to a quiet, voiceover-friendly level."""
    r = subprocess.run(
        ["ffmpeg", "-nostdin", "-y", "-i", src,
         "-af", f"loudnorm=I={i}:LRA={lra}:TP={tp}:print_format=json",
         "-f", "null", "-"],
        capture_output=True, text=True, timeout=180,
    )
    # ffmpeg prints the JSON on stderr
    err = r.stderr or ""
    start, end = err.rfind("{"), err.rfind("}")
    if start < 0 or end < 0:
        raise RuntimeError("loudnorm measurement failed:\n" + err[-800:])
    m = json.loads(err[start:end + 1])
    filt = (
        f"loudnorm=I={i}:LRA={lra}:TP={tp}:"
        f"measured_I={m['input_i']}:measured_LRA={m['input_lra']}:"
        f"measured_TP={m['input_tp']}:measured_thresh={m['input_thresh']}:"
        f"offset={m['target_offset']}:linear=true"
    )
    r2 = subprocess.run(
        ["ffmpeg", "-nostdin", "-y", "-i", src, "-af", filt,
         "-c:a", "pcm_s24le", "-ar", str(SR), "-ac",  "2", dst],
        capture_output=True, text=True, timeout=180,
    )
    if r2.returncode != 0:
        raise RuntimeError("loudnorm apply failed:\n" + (r2.stderr or "")[-800:])
    return m


def render_bed(seconds, out_wav, license_path=None, fade_in=2.0, fade_out=4.5, seed=1710):
    """Write a loopable, faded, loudnorm'd bed at least `seconds` long."""
    rng = np.random.default_rng(seed)
    loop = render_loop(rng)
    # Build slightly longer than needed so the fade-out has room, plus one loop of pad
    need = float(seconds) + 0.2
    n_need = int(math.ceil(need * SR))
    reps = int(math.ceil(n_need / len(loop))) + 1
    bed = np.tile(loop, (reps, 1))[:n_need]
    # fades (applied before loudnorm so the integrated loudness is of the faded bed)
    fi, fo = int(fade_in * SR), int(fade_out * SR)
    fi, fo = min(fi, n_need // 4), min(fo, n_need // 3)
    if fi > 0:
        bed[:fi] *= np.linspace(0, 1, fi)[:, None]
    if fo > 0:
        bed[-fo:] *= np.linspace(1, 0, fo)[:, None]
    tmp_dir = os.path.dirname(os.path.abspath(out_wav)) or "."
    os.makedirs(tmp_dir, exist_ok=True)
    raw = out_wav + ".raw.wav"
    write_wav(raw, bed)
    measured = loudnorm(raw, out_wav)
    try:
        os.remove(raw)
    except OSError:
        pass
    if license_path:
        open(license_path, "w").write(LICENSE_TEXT)
    return {
        "seconds": need,
        "bpm": BPM,
        "bars": BARS,
        "loop_seconds": LOOP_SEC,
        "target_lufs": TARGET_LUFS,
        "measured": {k: measured.get(k) for k in ("input_i", "input_tp", "input_lra") if k in measured},
        "license": "CC0 1.0 Universal",
        "source": "tools/edition-video/music.py (procedural synth, no third-party samples)",
        "seed": seed,
        "fade_in": fade_in,
        "fade_out": fade_out,
    }


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--seconds", type=float, default=LOOP_SEC * 2, help="Minimum length of the bed")
    p.add_argument("--out", default="music.wav")
    p.add_argument("--license", default=None)
    p.add_argument("--seed", type=int, default=1710)
    p.add_argument("--loop-only", action="store_true", help="Write a single unfaded 16-bar loop (for audition)")
    args = p.parse_args()
    if args.loop_only:
        rng = np.random.default_rng(args.seed)
        write_wav(args.out, render_loop(rng))
        print(f"wrote loop {args.out} ({LOOP_SEC:.1f}s)")
        return
    info = render_bed(args.seconds, args.out,
                      args.license or os.path.splitext(args.out)[0] + "-license.txt",
                      seed=args.seed)
    print(json.dumps(info, indent=2))


if __name__ == "__main__":
    main()
